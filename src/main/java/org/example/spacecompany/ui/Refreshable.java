package org.example.spacecompany.ui;

/**
 * Экран, умеющий перечитывать данные из сервисов и перерисовываться.
 * Главный контроллер вызывает {@link #refresh()} при показе экрана,
 * сами экраны — после каждого действия (покупка, запуск...).
 */
public interface Refreshable {

    /** Перечитать состояние из сервисов и обновить все надписи/таблицы. */
    void refresh();
}
