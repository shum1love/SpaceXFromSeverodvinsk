package org.example.spacecompany.domain;

/**
 * Возможные состояния {@link Rocket} за её жизнь.
 *
 * <p>Используем enum вместо строк/чисел: невозможное состояние нельзя даже
 * представить, а {@code switch} по статусам получается полным и читаемым.
 */
public enum RocketStatus {
    /** Заправлена и цела: можно назначать на миссию и запускать. */
    READY,
    /** Мало топлива. Сначала заправьте. */
    NO_FUEL,
    /** Выведена из строя на плановое обслуживание. Лететь нельзя. */
    IN_MAINTENANCE,
    /** Повреждена, но чинится. До ремонта лететь нельзя. */
    DAMAGED,
    /** Потеряна навсегда. Больше не используется. */
    DESTROYED,
    /** Выполняет миссию. До возвращения не трогать. */
    ON_MISSION
}
